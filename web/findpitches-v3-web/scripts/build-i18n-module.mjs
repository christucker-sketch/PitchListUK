// The Worker and browser share exactly the same catalog and language/path rules.
import fs from 'node:fs';
const root=new URL('../',import.meta.url);
const sources=['public/assets/js/locales.js','public/assets/js/i18n.js'];
const code=sources.map(p=>fs.readFileSync(new URL(p,root),'utf8')).join('\n');
fs.writeFileSync(new URL('server/i18n.mjs',root),'// GENERATED by scripts/build-i18n-module.mjs.\nconst window={};\n'+code+'\nexport const i18n=window.FP.i18n;\nexport const catalogs=window.FP_LOCALES;\n');
console.log('server/i18n.mjs written');
