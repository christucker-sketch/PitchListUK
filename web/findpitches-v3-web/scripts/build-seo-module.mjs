// Generates server/seo-edge.mjs: the site's routing + SEO logic (the same files the browser uses) as one ES module,
// so a V3 Worker / server can render titles, canonicals, robots, hreflang, JSON-LD, redirects, 404s and sitemaps.
//   node scripts/build-seo-module.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const parts = ['public/assets/js/routes.js', 'public/assets/js/seo/seo-config.js', 'public/assets/js/seo/seo-core.js']
  .map(f => `// ---- ${f}\n` + fs.readFileSync(path.join(root, f), 'utf8'));
const out = `// GENERATED by scripts/build-seo-module.mjs from public/assets/js/{routes.js,seo/seo-config.js,seo/seo-core.js}. Do not edit.
// Pure functions, no DOM and no network: safe in Cloudflare Workers, Node or any server renderer.
const window = { FP: {} };
${parts.join('\n')}
export const routes = window.FP.routes;
export const seoConfig = window.FP.seoConfig;
export const seo = window.FP.seo;
`;
fs.mkdirSync(path.join(root, 'server'), { recursive: true });
fs.writeFileSync(path.join(root, 'server', 'seo-edge.mjs'), out);
console.log('server/seo-edge.mjs written');
